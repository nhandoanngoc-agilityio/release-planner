#!/usr/bin/env python3
"""Write <folder>/scorecard.md from the tickets, intake.md and recall.md.

Usage: python scripts/score_kickoff.py intent/<folder>

Scores (see CONTEXT.md):
- Per ticket and Dev round: blocking and non-blocking questions raised.
- A ticket is ready at round n when the round-n Dev raised no blocking question
  and none is open. Round 1 readiness is the main measure of ticket quality.
- Totals: QA questions, questions sent back to the client, BA decisions.
- After the reveal (recall.md exists): BA recall over all and over hidden requirements.

The scorecard is generated: edit the inputs, not the scorecard.
"""

from __future__ import annotations

import re
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lint_tickets import Ticket, load_tickets, sections  # noqa: E402


def ready_round(t: Ticket) -> int | None:
    """First Dev round that raised no blocking question, if nothing is still open."""
    if t.open_blocking:
        return None
    for n in range(1, t.dev_rounds + 1):
        if not any(q.blocking and q.source == "dev" and q.iteration == n for q in t.questions):
            return n
    return None


def count(t: Ticket, blocking: bool, source: str, iteration: int | None = None) -> int:
    return sum(
        1
        for q in t.questions
        if q.blocking == blocking
        and q.source == source
        and (iteration is None or q.iteration == iteration)
    )


def intake_numbers(folder: Path) -> dict[str, int | bool]:
    path = folder / "intake.md"
    if not path.exists():
        return {"open_questions": 0, "dev_round_client": 0, "decisions": 0, "contradiction": False}
    secs = sections(path.read_text(encoding="utf-8"))

    def blocks(name: str) -> int:
        return len(re.findall(r"^### ", secs.get(name, ""), re.M))

    contradictions = secs.get("Contradictions", "").strip()
    return {
        "open_questions": blocks("Open questions"),
        "dev_round_client": blocks("Questions for the client (dev round)"),
        "decisions": len(re.findall(r"^- D\d+", secs.get("BA decisions", ""), re.M)),
        "contradiction": bool(contradictions) and not contradictions.lower().startswith("none"),
    }


def recall_rows(folder: Path) -> list[dict[str, str]]:
    path = folder / "recall.md"
    if not path.exists():
        return []
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 5 and re.fullmatch(r"H\d+", cells[0]):
            rows.append({"h": cells[0], "hidden": cells[2].lower(), "verdict": cells[4].lower()})
    return rows


def pct(part: float, whole: int) -> str:
    return f"{part:g}/{whole} ({part / whole:.0%})" if whole else "n/a"


def recall_line(rows: list[dict[str, str]]) -> tuple[str, str]:
    def score(subset: list[dict[str, str]]) -> str:
        got = sum(1.0 if r["verdict"] == "covered" else 0.5 if r["verdict"] == "partial" else 0 for r in subset)
        return pct(got, len(subset))

    core = [r for r in rows if r["hidden"] != "added"]
    hidden = [r for r in core if r["hidden"] == "yes"]
    return score(core), score(hidden)


def render(folder: Path) -> str:
    tickets = load_tickets(folder)
    max_round = max([t.dev_rounds for t in tickets] + [0])
    intake = intake_numbers(folder)
    rows = recall_rows(folder)

    out = [
        f"# Scorecard: {folder.name}",
        "",
        f"Generated by `scripts/score_kickoff.py` at {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC. "
        "Don't edit by hand.",
        "",
        "## Tickets",
        "",
    ]
    if not tickets:
        out.append("No tickets yet.")
    else:
        head = ["Ticket", "QA [B]"] + [f"Round {n} [B]/[N]" for n in range(1, max_round + 1)]
        head += ["Open [B]", "Ready at", "Status"]
        out.append("| " + " | ".join(head) + " |")
        out.append("|" + "---|" * len(head))
        for t in tickets:
            cells = [t.number, str(count(t, True, "qa"))]
            for n in range(1, max_round + 1):
                cells.append(
                    f"{count(t, True, 'dev', n)}/{count(t, False, 'dev', n)}" if n <= t.dev_rounds else "-"
                )
            rr = ready_round(t)
            cells += [str(len(t.open_blocking)), f"round {rr}" if rr else "not ready", t.status]
            out.append("| " + " | ".join(cells) + " |")

    ready = [ready_round(t) for t in tickets]
    out += [
        "",
        "## Totals",
        "",
        f"- Ready at round 1: {pct(ready.count(1), len(tickets))}",
        f"- Ready at round 2: {ready.count(2)} · round 3: {ready.count(3)} · not ready: {ready.count(None)}",
        f"- Blocking questions from Devs: {sum(count(t, True, 'dev') for t in tickets)} "
        f"· from QA: {sum(count(t, True, 'qa') for t in tickets)}",
        f"- Open questions sent to the client at intake: {intake['open_questions']}"
        f" · during the Dev round: {intake['dev_round_client']}",
        f"- BA decisions: {intake['decisions']} in intake, "
        f"{sum(1 for t in tickets for q in t.questions if 'BA decision:' in q.text)} in tickets",
        f"- Contradiction flagged by the BA: {'yes' if intake['contradiction'] else 'no'}",
        "",
        "## Recall",
        "",
    ]
    if rows:
        overall, hidden = recall_line(rows)
        missed = [r["h"] for r in rows if r["verdict"] == "missed"]
        out += [
            f"- BA recall: {overall} (partial counts as half)",
            f"- Hidden requirements recall: {hidden}",
            f"- Missed: {', '.join(missed) if missed else 'none'}",
        ]
    else:
        out.append("Not revealed yet: `recall.md` is written at the reveal stage.")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 1 or not Path(argv[0]).is_dir():
        print("usage: python scripts/score_kickoff.py intent/<folder>", file=sys.stderr)
        return 2
    folder = Path(argv[0])
    text = render(folder)
    (folder / "scorecard.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
